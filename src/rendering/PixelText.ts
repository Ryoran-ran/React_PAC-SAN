export function pixelText(
  context: CanvasRenderingContext2D, text: string, x: number, y: number,
  color: string, align: 'left' | 'center' | 'right' = 'left',
): void {
  const width = text.length * 6 - 1;
  const start = Math.round(x - (align === 'center' ? width / 2 : align === 'right' ? width : 0));
  context.fillStyle = color;
  [...text.toUpperCase()].forEach((letter, letterIndex) => {
    const glyph = GLYPHS[letter];
    if (!glyph) return;
    for (let i = 0; i < glyph.length; i++) {
      if (glyph[i] === '1') context.fillRect(start + letterIndex * 6 + i % 5, y + Math.floor(i / 5), 1, 1);
    }
  });
}
